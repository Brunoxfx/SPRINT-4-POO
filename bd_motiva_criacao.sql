CREATE TABLE TB_EQUIPE_MANUTENCAO (
    ID_EQUIPE NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    QUANTIDADE_INTEGRANTES NUMBER(3) NOT NULL,
    ESPECIALIDADE VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_EQUIPE PRIMARY KEY (ID_EQUIPE),
    CONSTRAINT UK_EQUIPE_NOME UNIQUE (NOME),
    CONSTRAINT CK_EQUIPE_QTD CHECK (QUANTIDADE_INTEGRANTES > 0)
);
CREATE TABLE TB_TRECHO_RODOVIA (
    ID_TRECHO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    KM_INICIAL NUMBER(10, 2) NOT NULL,
    KM_FINAL NUMBER(10, 2) NOT NULL,
    ALTURA_VEGETACAO_CM NUMBER(10, 2) NOT NULL,
    TIPO_AMBIENTE VARCHAR2(20) NOT NULL,
    RISCO_OPERACIONAL VARCHAR2(20) NOT NULL,
    ID_EQUIPE NUMBER,
    CONSTRAINT PK_TRECHO PRIMARY KEY (ID_TRECHO),
    CONSTRAINT UK_TRECHO_KM UNIQUE (KM_INICIAL, KM_FINAL),
    CONSTRAINT CK_TRECHO_KM CHECK (KM_INICIAL >= 0 AND KM_FINAL > KM_INICIAL),
    CONSTRAINT CK_TRECHO_ALTURA CHECK (ALTURA_VEGETACAO_CM >= 0),
    CONSTRAINT CK_TRECHO_AMBIENTE CHECK (TIPO_AMBIENTE IN ('seco', 'umido')),
    CONSTRAINT CK_TRECHO_RISCO CHECK (RISCO_OPERACIONAL IN ('baixo', 'alto')),
    CONSTRAINT FK_TRECHO_EQUIPE FOREIGN KEY (ID_EQUIPE)
        REFERENCES TB_EQUIPE_MANUTENCAO (ID_EQUIPE)
);

CREATE TABLE TB_INTERVENCAO_OPERACIONAL (
    ID_INTERVENCAO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TIPO VARCHAR2(30) NOT NULL,
    ID_TRECHO NUMBER NOT NULL,
    ID_EQUIPE NUMBER,
    CONSTRAINT PK_INTERVENCAO PRIMARY KEY (ID_INTERVENCAO),
    CONSTRAINT CK_INTERVENCAO_TIPO CHECK (
        TIPO IN ('ROCADA_MANUAL', 'ROCADA_MECANIZADA', 'PULVERIZACAO')
    ),
    CONSTRAINT FK_INTERVENCAO_TRECHO FOREIGN KEY (ID_TRECHO)
        REFERENCES TB_TRECHO_RODOVIA (ID_TRECHO),
    CONSTRAINT FK_INTERVENCAO_EQUIPE FOREIGN KEY (ID_EQUIPE)
        REFERENCES TB_EQUIPE_MANUTENCAO (ID_EQUIPE)
);

CREATE TABLE TB_RELATORIO_PRIORIDADE (
    ID_RELATORIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    QUANTIDADE_URGENTE NUMBER(10) DEFAULT 0 NOT NULL,
    QUANTIDADE_CRITICO NUMBER(10) DEFAULT 0 NOT NULL,
    QUANTIDADE_ATENCAO NUMBER(10) DEFAULT 0 NOT NULL,
    QUANTIDADE_NORMAL NUMBER(10) DEFAULT 0 NOT NULL,
    RESUMO VARCHAR2(4000) NOT NULL,
    DATA_GERACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_RELATORIO PRIMARY KEY (ID_RELATORIO),
    CONSTRAINT CK_RELATORIO_QTD CHECK (
        QUANTIDADE_URGENTE >= 0
        AND QUANTIDADE_CRITICO >= 0
        AND QUANTIDADE_ATENCAO >= 0
        AND QUANTIDADE_NORMAL >= 0
    )
);
